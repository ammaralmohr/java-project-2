    private void formWindowOpened(java.awt.event.WindowEvent evt) {//GEN-FIRST:event_formWindowOpened
        clearData();
        proj.getAllRows(tblProject);
        go.fillCombo("Department", "Dept_name", cbxDepartment);
        tblProject.getTableHeader().setReorderingAllowed(false);
        
    }//GEN-LAST:event_formWindowOpened

    private void btnUpdateActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnUpdateActionPerformed
        setValues();
        proj.update();
        proj.getAllRows(tblProject);
        clearData();
    }//GEN-LAST:event_btnUpdateActionPerformed

    private void btnDeleteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDeleteActionPerformed
        if(Tools.confirmMsg("Do You Want To Delete....")){
            setValues();
            proj.delete();
            proj.getAllRows(tblProject);
            clearData();
        }
    }//GEN-LAST:event_btnDeleteActionPerformed

    private void tblProjectMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tblProjectMouseClicked
        try{
            int row = tblProject.getSelectedRow();
            txtNumber.setText(tblProject.getValueAt(row, 0).toString());
            txtName.setText(tblProject.getValueAt(row, 1).toString());
            txtLocation.setText(tblProject.getValueAt(row, 2).toString());
            cbxDepartment.setSelectedItem(tblProject.getValueAt(row, 4));
            
            btnAdd.setEnabled(false);
            btnUpdate.setEnabled(true);
            btnDelete.setEnabled(true);
            
            
        }
        catch (Exception ex){
            Tools.msgBox(ex.getMessage());
        }
    }//GEN-LAST:event_tblProjectMouseClicked

    private void jMyButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jMyButton1ActionPerformed
        try{
            String strSelect = "select * from project_data where ";
            if(rdoNumber.isSelected())
                strSelect += "project_no ";
            else if (rdoName.isSelected())
                strSelect += "project_name ";
            else if (rdoLocation.isSelected())
                strSelect += "location ";
            else
                strSelect += "department like '%"+ txtSearch.getText() +"%' or"
                        + " department_no ";
            strSelect += "like '%"+ txtSearch.getText()+"%'";
            proj.getCustomRows(strSelect, tblProject);
            
        }
        catch (Exception ex){
            Tools.msgBox(ex.getMessage());
        }
    }//GEN-LAST:event_jMyButton1ActionPerformed

