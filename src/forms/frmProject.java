    private void clearData(){
        Tools.ClearText(this);
        btnAdd.setEnabled(true);
        btnUpdate.setEnabled(false);
        btnDelete.setEnabled(false);
        txtName.requestFocus();
        txtNumber.setText(proj.getAutoNumber());
    }
    
    private void setValues(){
        try {
            proj.setProject_no(Integer.parseInt(txtNumber.getText()));
            proj.setProject_name(txtName.getText());
            proj.setLocation(txtLocation.getText());
            
            String deptName = cbxDepartment.getSelectedItem().toString();
            String deptNo = dept.getValueByName(deptName);
            proj.setDept_no(Integer.parseInt(deptNo));
        
        }
        catch (Exception ex){
            Tools.msgBox(ex.getMessage());
        }
    }
    private void btnAddActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAddActionPerformed
        setValues();
        proj.add();
        proj.getAllRows(tblProject);
        clearData();
    }//GEN-LAST:event_btnAddActionPerformed

    private void btnFindActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnFindActionPerformed
        String number =(String) Tools.InputBox("Enter Project Number...");
        int projNum = Integer.parseInt(number);
        proj.setProject_no(projNum);
        proj.getOneRow(tblProject);
    }//GEN-LAST:event_btnFindActionPerformed

