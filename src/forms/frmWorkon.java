    private void setValues(){
        try{
            String emp_name = (String)cbxEmployee.getSelectedItem();
            workon.setEmp_no(Integer.parseInt(new Employee().getValueByName(emp_name)));
            String project_name = (String) cbxProject.getSelectedItem();
            workon.setProject_no(Integer.parseInt(new Project().getValueByName(project_name)));
        }
        catch (NumberFormatException ex){
            Tools.msgBox(ex.getMessage());
        }

    }
    private void setSelectValues(){
           try {
               int row = tblWorkon.getSelectedRow();
               String emp_no = (String)tblWorkon.getValueAt(row, 0);
               String proj_no =(String) tblWorkon.getValueAt(row, 2);
               workon.setEmp_no(Integer.parseInt(emp_no));
               workon.setProject_no(Integer.parseInt(proj_no));
           }
           catch(NumberFormatException ex){
               Tools.msgBox(ex.getMessage());
           }
        }
