    private void btnSearchActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSearchActionPerformed
        String strSelect = "select * from work_on_data where ";
        if(rdoEmpNo.isSelected())
            strSelect += "employee_no ";
        else if (rdoEmpName.isSelected())
            strSelect += "employee_name ";
        else if (rdoProjectNo.isSelected())
            strSelect += "project_no ";
        else
            strSelect += "project_name ";
        strSelect += "like '%" +txtSearch.getText() + "%'";
        workon.getCustomRows(strSelect, tblWorkon);
    }//GEN-LAST:event_btnSearchActionPerformed

